BEGIN TRY

BEGIN TRAN;

-- 1. USERS: estado de cuenta y control de intentos
ALTER TABLE [dbo].[USERS] ADD
    [IS_ACTIVE] BIT NOT NULL CONSTRAINT [DF_USERS_ACTIVE] DEFAULT (1),
    [FAILED_LOGIN_ATTEMPTS] TINYINT NOT NULL CONSTRAINT [DF_USERS_FAILED_ATTEMPTS] DEFAULT (0),
    [LOCKED_UNTIL] DATETIME2 NULL,
    [LAST_LOGIN_AT] DATETIME2 NULL;

ALTER TABLE [dbo].[USERS] ADD CONSTRAINT [CK_USERS_ROLE]
    CHECK ([ROLE] IN (N'ALUMNO', N'PROFESOR', N'ADMINISTRADOR'));

-- 2. AUDIT_LOG: auditoría genérica para todos los RF
CREATE TABLE [dbo].[AUDIT_LOG] (
    [AUDIT_LOG_ID] INT IDENTITY(1,1) NOT NULL,
    [USER_ID] INT NULL,
    [ACTION] NVARCHAR(50) NOT NULL,
    [ENTITY] NVARCHAR(50) NULL,
    [ENTITY_ID] NVARCHAR(50) NULL,
    [DETAILS] NVARCHAR(1000) NULL,
    [IP_ADDRESS] NVARCHAR(45) NULL,
    [CREATED_AT] DATETIME2 NOT NULL CONSTRAINT [DF_AUDIT_LOG_CREATED_AT] DEFAULT (SYSUTCDATETIME()),
    CONSTRAINT [PK_AUDIT_LOG] PRIMARY KEY CLUSTERED ([AUDIT_LOG_ID]),
    CONSTRAINT [FK_AUDIT_LOG_USERS] FOREIGN KEY ([USER_ID]) REFERENCES [dbo].[USERS]([USER_ID]) ON DELETE NO ACTION ON UPDATE NO ACTION
);

CREATE NONCLUSTERED INDEX [IX_AUDIT_LOG_USER] ON [dbo].[AUDIT_LOG] ([USER_ID]);
CREATE NONCLUSTERED INDEX [IX_AUDIT_LOG_CREATED_AT] ON [dbo].[AUDIT_LOG] ([CREATED_AT] DESC);

COMMIT TRAN;

END TRY
BEGIN CATCH

IF @@TRANCOUNT > 0
BEGIN
    ROLLBACK TRAN;
END;
THROW

END CATCH
