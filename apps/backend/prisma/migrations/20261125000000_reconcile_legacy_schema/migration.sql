BEGIN TRY
BEGIN TRAN;

-- The first three migrations were originally baselined over a db-push schema.
-- Fresh databases execute their older SQL, so reconcile those empty legacy tables.
-- Refuse to guess a mapping for populated, unsupported schemas.
IF COL_LENGTH('dbo.STUDY_PLAN', 'PLAN_CODE') IS NOT NULL
BEGIN
    IF EXISTS (SELECT 1 FROM [dbo].[STUDY_PLAN])
        THROW 51000, 'Legacy STUDY_PLAN has data. Reconcile its resolution and plan metadata before deploying; no rows were changed.', 1;
    ALTER TABLE [dbo].[STUDY_PLAN] DROP CONSTRAINT [UQ_STUDY_PLAN_CODE];
    ALTER TABLE [dbo].[STUDY_PLAN] DROP COLUMN [PLAN_CODE], [RESOLUTION_NUMBER], [TOTAL_SUBJECTS], [TOTAL_HOURS];
    ALTER TABLE [dbo].[STUDY_PLAN] ADD [RESOLUTION] NVARCHAR(100) NOT NULL;
END;

IF COL_LENGTH('dbo.STUDENT_CAREER', 'ENROLLMENT_YEAR') IS NOT NULL
    EXEC sp_rename 'dbo.STUDENT_CAREER.ENROLLMENT_YEAR', 'ADMISSION_YEAR', 'COLUMN';
IF COL_LENGTH('dbo.STUDENT_CAREER', 'STUDENT_CAREER_STATUS') IS NOT NULL
    EXEC sp_rename 'dbo.STUDENT_CAREER.STUDENT_CAREER_STATUS', 'ACADEMIC_STATUS', 'COLUMN';

IF COL_LENGTH('dbo.EXAM_SESSION', 'ACADEMIC_PERIOD_ID') IS NOT NULL
BEGIN
    IF EXISTS (SELECT 1 FROM [dbo].[EXAM_SESSION])
        THROW 51000, 'Legacy EXAM_SESSION has data. Reconcile its period before deploying; no rows were changed.', 1;
    ALTER TABLE [dbo].[EXAM_SESSION] DROP CONSTRAINT [FK_ES_PERIOD];
    DROP INDEX [IX_ES_PERIOD] ON [dbo].[EXAM_SESSION];
    ALTER TABLE [dbo].[EXAM_SESSION] DROP COLUMN [ACADEMIC_PERIOD_ID], [SESSION_NAME];
    ALTER TABLE [dbo].[EXAM_SESSION] ADD [EXAM_NAME] NVARCHAR(100) NOT NULL, [EXAM_YEAR] SMALLINT NOT NULL, [SESSION_STATUS] NVARCHAR(30) NOT NULL;
END;

IF COL_LENGTH('dbo.STUDENT_STUDY_PLAN', 'STUDY_PLAN_STATUS') IS NOT NULL
BEGIN
    IF EXISTS (SELECT 1 FROM [dbo].[STUDENT_STUDY_PLAN])
        THROW 51000, 'Legacy STUDENT_STUDY_PLAN has data. Reconcile its status before deploying; no rows were changed.', 1;
    ALTER TABLE [dbo].[STUDENT_STUDY_PLAN] DROP CONSTRAINT [DF_SSP_DATE];
    DROP INDEX [IX_SSP_STUDY_PLAN] ON [dbo].[STUDENT_STUDY_PLAN];
    ALTER TABLE [dbo].[STUDENT_STUDY_PLAN] DROP COLUMN [ASSIGNMENT_DATE], [STUDY_PLAN_STATUS];
END;

-- Copy actual editable metadata out of the redundant columns. Never copy the
-- manually entered student counter: enrollment counts come from COURSE_ENROLLMENT.
EXEC(N'UPDATE p SET [RESOLUTION] = c.[STUDY_PLAN]
FROM [dbo].[STUDY_PLAN] p
JOIN [dbo].[CAREERS] c ON c.[CAREER_ID] = p.[CAREER_ID]
WHERE p.[IS_ACTIVE] = 1 AND NULLIF(LTRIM(RTRIM(c.[STUDY_PLAN])), '''') IS NOT NULL;');

UPDATE [dbo].[STUDY_PLAN_SUBJECT]
SET [SEMESTER] = CASE [PERIOD] WHEN N'anual' THEN 0 WHEN N'1' THEN 1 WHEN N'2' THEN 2 END
WHERE [PERIOD] IN (N'anual', N'1', N'2') AND [SUBJECT_YEAR] IS NOT NULL;

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID('dbo.EXAM_ENROLLMENT') AND name = 'IX_EE_STUDENT_CAREER')
    CREATE NONCLUSTERED INDEX [IX_EE_STUDENT_CAREER] ON [dbo].[EXAM_ENROLLMENT] ([STUDENT_CAREER_ID]);

COMMIT TRAN;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRAN;
    THROW;
END CATCH;
