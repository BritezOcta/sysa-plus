BEGIN TRY

BEGIN TRAN;

-- 1. CAREERS: duración, descripción, estado y última modificación
IF COL_LENGTH('dbo.CAREERS', 'DURATION_YEARS') IS NULL
    ALTER TABLE [dbo].[CAREERS] ADD [DURATION_YEARS] TINYINT NOT NULL
        CONSTRAINT [DF_CAREERS_DURATION] DEFAULT (5);

IF COL_LENGTH('dbo.CAREERS', 'CAREER_DESCRIPTION') IS NULL
    ALTER TABLE [dbo].[CAREERS] ADD [CAREER_DESCRIPTION] NVARCHAR(500) NULL;

IF COL_LENGTH('dbo.CAREERS', 'IS_ACTIVE') IS NULL
    ALTER TABLE [dbo].[CAREERS] ADD [IS_ACTIVE] BIT NOT NULL
        CONSTRAINT [DF_CAREERS_ACTIVE] DEFAULT (1);

IF COL_LENGTH('dbo.CAREERS', 'UPDATED_AT') IS NULL
    ALTER TABLE [dbo].[CAREERS] ADD [UPDATED_AT] DATETIME2 NOT NULL
        CONSTRAINT [DF_CAREERS_UPDATED_AT] DEFAULT (SYSUTCDATETIME());

-- 2. STUDY_PLAN_SUBJECT: estado y año opcional (materia "sin asignar")
IF COL_LENGTH('dbo.STUDY_PLAN_SUBJECT', 'IS_ACTIVE') IS NULL
    ALTER TABLE [dbo].[STUDY_PLAN_SUBJECT] ADD [IS_ACTIVE] BIT NOT NULL
        CONSTRAINT [DF_SPS_ACTIVE] DEFAULT (1);

ALTER TABLE [dbo].[STUDY_PLAN_SUBJECT] ALTER COLUMN [SUBJECT_YEAR] TINYINT NULL;

-- 3. SUBJECT_CORRELATIVITY: tipo de correlatividad y fecha de alta
IF COL_LENGTH('dbo.SUBJECT_CORRELATIVITY', 'CORRELATIVITY_TYPE') IS NULL
    ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] ADD [CORRELATIVITY_TYPE] NVARCHAR(30) NOT NULL
        CONSTRAINT [DF_CORR_TYPE_TMP] DEFAULT (N'regularizada_cursar');

IF COL_LENGTH('dbo.SUBJECT_CORRELATIVITY', 'CREATED_AT') IS NULL
    ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] ADD [CREATED_AT] DATETIME2 NOT NULL
        CONSTRAINT [DF_CORRELATIVITY_CREATED_AT] DEFAULT (SYSUTCDATETIME());

-- 4. Correlatividades: el tipo pasa a formar parte de la clave única
IF EXISTS (SELECT 1 FROM sys.default_constraints WHERE name = 'DF_CORR_TYPE_TMP')
    ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] DROP CONSTRAINT [DF_CORR_TYPE_TMP];

IF EXISTS (SELECT 1 FROM sys.key_constraints WHERE name = 'UQ_CORRELATIVITY')
    ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] DROP CONSTRAINT [UQ_CORRELATIVITY];

ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] ADD CONSTRAINT [UQ_CORRELATIVITY]
    UNIQUE ([TARGET_SUBJECT_ID], [REQUIRED_SUBJECT_ID], [CORRELATIVITY_TYPE]);

COMMIT TRAN;

END TRY
BEGIN CATCH

IF @@TRANCOUNT > 0
BEGIN
    ROLLBACK TRAN;
END;
THROW

END CATCH
