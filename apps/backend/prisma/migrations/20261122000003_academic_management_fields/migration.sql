BEGIN TRY

BEGIN TRAN;

-- 1. CAREERS: campo de resolución / plan de estudio
IF COL_LENGTH('dbo.CAREERS', 'STUDY_PLAN') IS NULL
    ALTER TABLE [dbo].[CAREERS] ADD [STUDY_PLAN] NVARCHAR(100) NULL;

-- 2. STUDY_PLAN_SUBJECT: carrera directa, régimen/cuatrimestre ('1', '2', 'anual') y contador de alumnos
IF COL_LENGTH('dbo.STUDY_PLAN_SUBJECT', 'CAREER_ID') IS NULL
    ALTER TABLE [dbo].[STUDY_PLAN_SUBJECT] ADD [CAREER_ID] INT NULL
        CONSTRAINT [FK_SPS_CAREER_DIRECT] REFERENCES [dbo].[CAREERS] ([CAREER_ID]);

IF COL_LENGTH('dbo.STUDY_PLAN_SUBJECT', 'PERIOD') IS NULL
    ALTER TABLE [dbo].[STUDY_PLAN_SUBJECT] ADD [PERIOD] NVARCHAR(20) NULL;

IF COL_LENGTH('dbo.STUDY_PLAN_SUBJECT', 'ENROLLED_STUDENTS') IS NULL
    ALTER TABLE [dbo].[STUDY_PLAN_SUBJECT] ADD [ENROLLED_STUDENTS] INT NOT NULL
        CONSTRAINT [DF_SPS_ENROLLED] DEFAULT (0);

-- 3. SUBJECT_CORRELATIVITY: carrera directa para consultas ágiles por carrera
IF COL_LENGTH('dbo.SUBJECT_CORRELATIVITY', 'CAREER_ID') IS NULL
    ALTER TABLE [dbo].[SUBJECT_CORRELATIVITY] ADD [CAREER_ID] INT NULL
        CONSTRAINT [FK_CORR_CAREER] REFERENCES [dbo].[CAREERS] ([CAREER_ID]);

-- 4. AUDIT_LOG: resumen textual y nombre/rol amigable del usuario para auditoría académica
IF COL_LENGTH('dbo.AUDIT_LOG', 'SUMMARY') IS NULL
    ALTER TABLE [dbo].[AUDIT_LOG] ADD [SUMMARY] NVARCHAR(255) NULL;

IF COL_LENGTH('dbo.AUDIT_LOG', 'USER_NAME') IS NULL
    ALTER TABLE [dbo].[AUDIT_LOG] ADD [USER_NAME] NVARCHAR(100) NULL;

IF COL_LENGTH('dbo.AUDIT_LOG', 'USER_ROLE') IS NULL
    ALTER TABLE [dbo].[AUDIT_LOG] ADD [USER_ROLE] NVARCHAR(50) NULL;

COMMIT TRAN;

END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRAN;
    THROW;
END CATCH;
